#!/usr/bin/env python3
"""
Golden pages for sflink_test.cpp: a short, real record in the Static Fire
Stand's on-flash format, built and decoded by the stand's OWN Python tools, so
that the C++ code on Ariadna is checked against the other implementation of
the same format rather than against itself.

    python3 gen_sflink_golden.py --stand ../../Static_Fire_Stand > sflink_golden.h
"""
import argparse
import sys
from pathlib import Path

import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--stand", default="../../Static_Fire_Stand",
                help="checkout of the Static_Fire_Stand repository")
args = ap.parse_args()
tools = Path(args.stand).resolve() / "tools"
sys.path.insert(0, str(tools))

import make_test_dump as mk                       # noqa: E402
from sf_protocol import decode_slot               # noqa: E402

mk.PREROLL_S = 0.5
mk.RECORD_S = 1.5
np.random.seed(11)
pages = mk.build(burn_id=41, delay=0.2, peak=180.0, burn=0.8, fuel_g=10.0, rate=80.0, cut_at=None)
burn = decode_slot(pages, 0)
df = burn.df

out = []
out.append("// Generated by gen_sflink_golden.py from Static_Fire_Stand/tools - do not edit.")
out.append("#pragma once")
out.append("#include <stdint.h>")
out.append(f"static const unsigned GOLD_PAGES = {len(pages)};")
out.append(f"static const unsigned GOLD_SAMPLES = {len(df)};")
out.append(f"static const float    GOLD_CAL = {burn.cal_counts_per_n:.6f}f;")
out.append(f"static const int32_t  GOLD_TARE = {burn.tare_offset};")
out.append(f"static const uint32_t GOLD_BURN_ID = {burn.burn_id};")
out.append("static const uint8_t GOLD_PAGE_DATA[%d][256] = {" % len(pages))
for p in pages:
    out.append("  {" + ",".join(str(b) for b in p) + "},")
out.append("};")
out.append("static const int32_t GOLD_T_US[%d] = {%s};" % (len(df), ",".join(str(int(v)) for v in (df["t"] * 1e6).round())))
out.append("static const int32_t GOLD_RAW[%d] = {%s};" % (len(df), ",".join(str(int(v)) for v in df["raw"])))
print("\n".join(out))
