# ---------------------------------------------------------------------------
#  USB CDC link to Position MCU (binary HIL frames + ASCII HELLO / HIL 0)
# ---------------------------------------------------------------------------
class PosHilLink:
    """Dedicated serial connection to Position MCU's USB CDC port (or DEMO)."""

    def __init__(self, demo_sink=None):
        self._ser = None
        self._lock = threading.Lock()
        self.port: str | None = None
        self.is_demo: bool = False
        self.fw_version: int = 0
        self.hil_supported: bool = False
        self.info_line: str = ""
        self._demo_sink = demo_sink

    @property
    def is_open(self) -> bool:
        return self.is_demo or (self._ser is not None and self._ser.is_open)

    def open(self, port: str, demo_sink=None) -> tuple[bool, str]:
        self.close()
        if demo_sink is not None:
            self._demo_sink = demo_sink
        if port == "DEMO":
            self.port = "DEMO"
            self.is_demo = True
            self.fw_version = 332
            self.hil_supported = True
            self.info_line = "I DAIDALOS_POS 332 HIL 1 (DEMO)"
            return True, self.info_line

        if serial is None:
            return False, "Chybí knihovna pyserial (pip install pyserial)."
        try:
            ser = serial.Serial(port, 115200, timeout=0.08, write_timeout=0.15)
        except Exception as exc:
            return False, f"Nelze otevřít {port}: {exc}"

        try:
            ser.reset_input_buffer()
            ser.reset_output_buffer()
            # Probe with HELLO; Position MCU fw >= 3.32 replies "I DAIDALOS_POS <fw> HIL 1"
            deadline = time.monotonic() + 1.2
            reply = ""
            next_probe = 0.0
            while time.monotonic() < deadline:
                now = time.monotonic()
                if now >= next_probe:
                    ser.write(b"HELLO\n")
                    ser.flush()
                    next_probe = now + 0.35
                raw = ser.readline()
                if not raw:
                    continue
                txt = raw.decode("ascii", errors="replace").strip()
                if txt.startswith("I DAIDALOS_POS"):
                    reply = txt
                    break
                if txt.startswith("I DAIDALOS "):
                    ser.close()
                    return False, (
                        f"Na portu {port} odpověděl Master MCU ({txt}), ne Position MCU! "
                        "Vyberte USB port desky Position MCU."
                    )
            if not reply:
                ser.close()
                return False, (
                    f"Port {port} neodpověděl na HELLO jako Position MCU (očekáváno I DAIDALOS_POS ≥332 HIL 1). "
                    "Zkontrolujte kabel a nahraný firmware ≥ 3.32."
                )
            parts = reply.split()
            fw = int(parts[2]) if len(parts) >= 3 and parts[2].isdigit() else 0
            hil_ok = ("HIL" in parts and parts[parts.index("HIL") + 1] == "1") if "HIL" in parts and parts.index("HIL") + 1 < len(parts) else False
            if fw < 332 or not hil_ok:
                ser.close()
                return False, f"Position MCU hlásí firmware {fw / 100:.2f} bez podpory HIL ({reply})."
            with self._lock:
                self._ser = ser
                self.port = port
                self.is_demo = False
                self.fw_version = fw
                self.hil_supported = True
                self.info_line = reply
            return True, reply
        except Exception as exc:
            try:
                ser.close()
            except Exception:
                pass
            return False, f"Chyba při ověřování Position MCU na {port}: {exc}"

    def send_frame(self, frame: bytes, sample: hs.HilSensorSample | None = None) -> bool:
        if self.is_demo:
            if self._demo_sink is not None and sample is not None:
                self._demo_sink(sample)
            return True
        with self._lock:
            if self._ser is None or not self._ser.is_open:
                return False
            try:
                self._ser.write(frame)
                return True
            except Exception:
                return False

    def send_ascii(self, cmd: str) -> None:
        if self.is_demo:
            return
        with self._lock:
            if self._ser is None or not self._ser.is_open:
                return
            try:
                self._ser.write((cmd.strip() + "\n").encode("ascii"))
                self._ser.flush()
            except Exception:
                pass

    def drain_ascii(self) -> list[str]:
        """Non-blocking read of any debug/OK lines emitted by Position MCU."""
        if self.is_demo:
            return []
        lines: list[str] = []
        with self._lock:
            if self._ser is None or not self._ser.is_open:
                return lines
            try:
                while self._ser.in_waiting:
                    raw = self._ser.readline()
                    if not raw:
                        break
                    txt = raw.decode("ascii", errors="replace").strip()
                    if txt:
                        lines.append(txt)
            except Exception:
                pass
        return lines

    def close(self) -> None:
        if self._ser is not None:
            try:
                self.send_ascii("HIL 0")
                time.sleep(0.03)
            except Exception:
                pass
            with self._lock:
                try:
                    self._ser.close()
                except Exception:
                    pass
                self._ser = None
        self.port = None
        self.is_demo = False
        self.fw_version = 0
        self.hil_supported = False
        self.info_line = ""


# ---------------------------------------------------------------------------
#  Small helper: local KV grid matching DiagWindow.KV
# ---------------------------------------------------------------------------
class _KV(QtWidgets.QWidget):
    def __init__(self, names: list[str]):
        super().__init__()
        g = QtWidgets.QGridLayout(self)
        g.setContentsMargins(0, 0, 0, 0)
        g.setHorizontalSpacing(14)
        g.setVerticalSpacing(3)
        self.v: dict[str, QtWidgets.QLabel] = {}
        for i, n in enumerate(names):
            g.addWidget(label(n, "muted"), i, 0)
            lab = label("—", "value")
            lab.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
            g.addWidget(lab, i, 1)
            self.v[n] = lab
        g.setColumnStretch(1, 1)

    def set(self, name: str, text: str, color: str | None = None) -> None:
        lab = self.v[name]
        if lab.text() != text:
            lab.setText(text)
        style = f"color: {color};" if color else ""
        if lab.styleSheet() != style:
            lab.setStyleSheet(style)


