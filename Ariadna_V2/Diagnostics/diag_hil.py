    # ------------------------------------------------------------ 100 Hz worker thread
    def _run_loop(self, cfg: hs.HilConfig, pyro_live: bool) -> None:
        dt = 0.01
        master_entered = False
        ok = False
        reason = ""
        csv_path = ""

        try:
            # ---- Phase 1: 5-second countdown (settle Position MCU KF on synthetic pad) ----
            t_cd0 = time.perf_counter()
            next_tick = t_cd0
            first_pkt = True
            while not self._stop_evt.is_set():
                now = time.perf_counter()
                elapsed = now - t_cd0
                left = max(0.0, self.COUNTDOWN_S - elapsed)
                with self._lock:
                    self._countdown_left = left

                samp = self.plant.make_pad_sample(reset_est=first_pkt, set_pad_ref=first_pkt)
                first_pkt = False
                if not self.pos_link.send_frame(hs.pack_hil_frame(samp), samp):
                    reason = "Selhal zápis do USB portu Position MCU během odpočtu."
                    break
                with self._lock:
                    self._pos_tx_count += 1

                if elapsed >= self.COUNTDOWN_S:
                    break
                next_tick += dt
                sleep_s = next_tick - time.perf_counter()
                if sleep_s > 0:
                    time.sleep(sleep_s)

            if self._stop_evt.is_set() or reason:
                raise _HilStop(reason or self._abort_reason or "Zrušeno během odpočtu.")

            # ---- Phase 2: Enter HIL on Master MCU (`HIL 1 0|1`) while keeping Position fed ----
            with self._lock:
                self._run_state = "ARMING"
            self._master_hil_evt.clear()
            self.sig_master_cmd.emit(f"HIL 1 {1 if pyro_live else 0}")

            arm_deadline = time.perf_counter() + 2.0
            next_tick = time.perf_counter()
            while not self._stop_evt.is_set():
                samp = self.plant.make_pad_sample()
                if not self.pos_link.send_frame(hs.pack_hil_frame(samp), samp):
                    raise _HilStop("Selhal zápis do Position MCU při aktivaci Master HIL.")
                with self._lock:
                    self._pos_tx_count += 1
                if self._master_hil_evt.is_set():
                    break
                if time.perf_counter() >= arm_deadline:
                    raise _HilStop("Master MCU neodpověděl na příkaz HIL 1 (timeout 2 s).")
                next_tick += dt
                sleep_s = next_tick - time.perf_counter()
                if sleep_s > 0:
                    time.sleep(sleep_s)

            if self._stop_evt.is_set():
                raise _HilStop(self._abort_reason or "Zastaveno.")
            if not self._master_hil_ok:
                raise _HilStop(f"Master MCU odmítl HIL: {self._master_hil_msg}")
            master_entered = True
            self.sig_log.emit(f"# HIL: Master potvrdil ({self._master_hil_msg}) — zahajuji let!")

            # Brief 150 ms settle so ARMED + SET_PAD_REF propagates before liftoff
            t_settle = time.perf_counter() + 0.15
            while time.perf_counter() < t_settle and not self._stop_evt.is_set():
                samp = self.plant.make_pad_sample()
                self.pos_link.send_frame(hs.pack_hil_frame(samp), samp)
                with self._lock:
                    self._pos_tx_count += 1
                time.sleep(dt)

            if self._stop_evt.is_set():
                raise _HilStop(self._abort_reason or "Zastaveno.")

            # ---- Phase 3: Simulated 6-DOF flight @ 100 Hz ----
            self.plant.launch()
            with self._lock:
                self._run_state = "RUNNING"

            next_tick = time.perf_counter()
            post_land_t0 = None
            hw_landed_t0 = None
            tick_i = 0

            while not self._stop_evt.is_set():
                with self._lock:
                    hw = self._latest_hw
                    have_h = self._h_rx_count > 0

                samp = self.plant.step(dt, hw if (cfg.mode == "closed" and have_h) else None)
                if not self.pos_link.send_frame(hs.pack_hil_frame(samp), samp):
                    raise _HilStop("Ztraceno spojení s Position MCU během letu.")
                self.recorder.record(self.plant, samp, hw)

                tick_i += 1
                with self._lock:
                    self._pos_tx_count += 1
                    if tick_i % 5 == 0:    # 20 Hz UI snapshot & chart points
                        true_tilt = hs.tilt_deg_from_quat(self.plant.q)
                        est_tilt = hs.tilt_deg_from_quat(hw.est_q)
                        self._live_snap = {
                            "sim_phase": self.plant.phase,
                            "t_sim": self.plant.t,
                            "true_pz": self.plant.pos[2],
                            "true_vz": self.plant.vel[2],
                            "true_tilt": true_tilt,
                            "hw": hw,
                            "est_tilt": est_tilt,
                        }
                        self._chart_buf.append((
                            self.plant.t,
                            self.plant.pos[2], hw.est_p[2],
                            true_tilt, est_tilt, math.degrees(hw.tilt_cmd),
                            hw.tvc_deg[0], hw.tvc_deg[1], hw.clamp * 10.0,
                            hw.fin_deg[0], hw.fin_deg[1], hw.fin_deg[2], hw.fin_deg[3],
                        ))

                # Check completion conditions
                if self.plant.phase == "LANDED":
                    with self._lock:
                        self._run_state = "POST_LAND"
                    if post_land_t0 is None:
                        post_land_t0 = time.perf_counter()
                    if have_h and hw.mst_state >= 7:
                        if hw_landed_t0 is None:
                            hw_landed_t0 = time.perf_counter()
                        if time.perf_counter() - hw_landed_t0 >= 0.35:
                            ok = True
                            reason = "Simulovaný let úspěšně dokončen (dosednutí potvrzeno Masterem)."
                            break
                    if time.perf_counter() - post_land_t0 >= self.POST_LAND_S:
                        ok = True
                        reason = "Simulovaný let dokončen (dosednutí)."
                        break

                if have_h and hw.mst_state in (9, 11):   # ABORT or ERROR on Master
                    reason = f"Master MCU přešel do stavu {hw.mst_state} (ABORT/ERROR)."
                    break
                if self.plant.t >= self.MAX_FLIGHT_S:
                    reason = f"Překročena maximální doba simulace ({self.MAX_FLIGHT_S:.0f} s)."
                    break

                next_tick += dt
                sleep_s = next_tick - time.perf_counter()
                if sleep_s > 0:
                    time.sleep(sleep_s)
                elif sleep_s < -0.1:
                    next_tick = time.perf_counter()

            if self._stop_evt.is_set() and not ok:
                reason = self._abort_reason or "Zastaveno uživatelem."

        except _HilStop as stop_exc:
            ok = False
            reason = str(stop_exc)
        except Exception as exc:
            ok = False
            reason = f"Neočekávaná chyba HIL simulace: {exc}"
        finally:
            # Always exit HIL cleanly on BOTH boards!
            if master_entered:
                self.sig_master_cmd.emit("HIL 0")
            self.pos_link.send_ascii("HIL 0")

            # Auto-save CSV whenever any flight data were recorded
            if self.recorder.rows:
                try:
                    os.makedirs(self.out_dir, exist_ok=True)
                    fname = time.strftime("hil_%Y%m%d_%H%M%S.csv")
                    csv_path = os.path.join(self.out_dir, fname)
                    self.recorder.save_csv(csv_path)
                    self.sig_log.emit(f"# HIL: data uložena do {csv_path} ({len(self.recorder.rows)} řádků)")
                except Exception as exc:
                    self.sig_log.emit(f"# HIL: chyba při ukládání CSV: {exc}")

            with self._lock:
                self._run_state = "IDLE"
                self._last_csv_path = csv_path
            self.sig_finished.emit(ok, reason, csv_path)

    # ------------------------------------------------------------ UI refresh (20 Hz)
    def _ui_tick(self) -> None:
        # Drain any ASCII replies from Position MCU into the diagnostic log
        for ln in self.pos_link.drain_ascii():
            self.win.log(f"[POS] {ln}")

        # Update readiness chips from Master's latest M / N lines
        M = self.win.d.get("M") if self.win._fresh_d("M") else {}
        N = self.win.d.get("N") if self.win._fresh_d("N") else {}

        m_ok = bool(M) and M.get("fw", 0) >= 332
        set_chip(self.chk_master,
                 f"Master fw {M.get('fw', 0) / 100:.2f}" if M else "Master: odpojeno",
                 "ok" if m_ok else ("warn" if M else ""))
        set_chip(self.chk_pos_usb,
                 f"Position USB ({self.pos_link.port})" if self.pos_link.is_open else "Position USB: odpojeno",
                 "ok" if self.pos_link.is_open else "")
        nav_ok = bool(M and M.get("nav") and M["nav"][2])
        set_chip(self.chk_nav, "Navigation: OK" if nav_ok else "Navigation: —", "ok" if nav_ok else ("bad" if M else ""))
        sync_ok = bool(M and M.get("psync"))
        set_chip(self.chk_sync, "Parametry: sync" if sync_ok else "Parametry: čeká", "ok" if sync_ok else ("warn" if M else ""))
        val_ok = bool(N and (N.get("fl", 0) & 1))
        set_chip(self.chk_valid, "Navigace: VALID" if val_ok else "Navigace: neplatná", "ok" if val_ok else ("warn" if N else ""))
        if M:
            rbf_out = bool(M.get("rbf"))
            set_chip(self.chk_rbf, "RBF: vytažen" if rbf_out else "RBF: zasunut",
                     "warn" if rbf_out else "ok")
        else:
            set_chip(self.chk_rbf, "RBF: —", "")

        # Live simulation banner, progress, KV, and charts
        with self._lock:
            state = self._run_state
            cd_left = self._countdown_left
            snap = dict(self._live_snap)
            tx_n = self._pos_tx_count
            rx_n = self._h_rx_count
            pts = list(self._chart_buf)
            self._chart_buf.clear()

        for pt in pts:
            t_s = pt[0]
            self.ch_alt.add(t_s, [pt[1], pt[2]])
            self.ch_tilt.add(t_s, [pt[3], pt[4], pt[5]])
            self.ch_tvc.add(t_s, [pt[6], pt[7], pt[8]])
            self.ch_fin.add(t_s, [pt[9], pt[10], pt[11], pt[12]])

        if state == "COUNTDOWN":
            sec_i = max(1, int(math.ceil(cd_left)))
            self.lbl_banner.setText(f"ODPOČET DO STARTU:  {sec_i} s   ({cd_left:.1f} s)")
            self.lbl_banner.setStyleSheet(
                f"font-size: 22px; font-weight: 700; color: {ag.C['accent']}; "
                f"background: {ag.C['accent_tint']}; border: 2px solid {ag.C['accent']}; "
                f"border-radius: 10px; padding: 8px;"
            )
            pct = int(round(100.0 * (self.COUNTDOWN_S - cd_left) / self.COUNTDOWN_S))
            self.prog.setValue(max(0, min(100, pct)))
            self.prog.setFormat(f"Usazování KF na rampě… {cd_left:.1f} s")
        elif state == "ARMING":
            self.lbl_banner.setText("AKTIVACE HIL NA MASTERU (HIL 1)…")
            self.prog.setFormat("Čekání na potvrzení Master MCU")
        elif state in ("RUNNING", "POST_LAND"):
            ph = snap.get("sim_phase", "ASCENT")
            t_sim = snap.get("t_sim", 0.0)
            self.lbl_banner.setText(f"SIMULOVANÝ LET · T+{t_sim:5.2f} s · {SIM_PHASE_CZ.get(ph, ph).upper()}")
            col = BAD if self.chk_pyro_en.isChecked() else GOOD
            self.lbl_banner.setStyleSheet(
                f"font-size: 20px; font-weight: 700; color: {col}; "
                f"background: {ag.C['surface']}; border: 2px solid {col}; "
                f"border-radius: 10px; padding: 8px;"
            )
            p_map = {"PAD": 5, "ASCENT": 25, "APOGEE_FLIP": 45, "DESCENT": 65, "IGNITING": 78, "BURN": 90, "LANDED": 100}
            self.prog.setValue(p_map.get(ph, 50))
            self.prog.setFormat(f"Fáze: {SIM_PHASE_CZ.get(ph, ph)}  (T+{t_sim:.1f} s)")

        if snap:
            hw: hs.HwFeedback = snap["hw"]
            st_names = {0: "BOOT", 1: "IDLE", 2: "ARMED", 3: "ASCENT", 4: "APOGEE", 5: "DESCENT",
                        6: "GUIDANCE", 7: "LANDED", 8: "RECOVERY", 9: "ABORT", 10: "TEST", 11: "ERROR"}
            ph_names = {0: "IDLE", 1: "ASCENT", 2: "DESCENT", 3: "IGNITING", 4: "BURN", 5: "DONE"}
            us = hw.servo_us if len(hw.servo_us) >= 8 else (0,) * 8
            self.live_kv.set(
                "Fáze sim / Master / Nav",
                f"{snap['sim_phase']}  /  {st_names.get(hw.mst_state, hw.mst_state)}  /  {ph_names.get(hw.nav_phase, hw.nav_phase)}",
            )
            self.live_kv.set("Výška pravá / odhad HW", f"{snap['true_pz']:6.2f} m  /  {hw.est_p[2]:6.2f} m")
            self.live_kv.set("Rychlost Vz pravá / HW", f"{snap['true_vz']:+6.2f} m/s  /  {hw.est_v[2]:+6.2f} m/s")
            self.live_kv.set(
                "Náklon pravý / HW / příkaz",
                f"{snap['true_tilt']:4.1f}°  /  {snap['est_tilt']:4.1f}°  /  {math.degrees(hw.tilt_cmd):4.1f}°",
            )
            self.live_kv.set(
                "TVC X / Y (°  |  µs)",
                f"{hw.tvc_deg[0]:+5.2f}° / {hw.tvc_deg[1]:+5.2f}°   |   {us[0]} / {us[1]} µs",
            )
            self.live_kv.set("Klapka (%  |  µs)", f"{hw.clamp * 100.0:5.1f} %   |   {us[2]} µs")
            self.live_kv.set(
                "Křidélka 1–4 (°)",
                f"{hw.fin_deg[0]:+5.1f}  {hw.fin_deg[1]:+5.1f}  {hw.fin_deg[2]:+5.1f}  {hw.fin_deg[3]:+5.1f} °",
            )
            pa_txt = ",".join(f"P{i+1}" for i in range(3) if hw.pyro_active & (1 << i)) or "—"
            pf_txt = ",".join(f"P{i+1}" for i in range(3) if hw.pyro_fired & (1 << i)) or "—"
            cov_txt = "ODJIŠTĚN" if hw.cover_open else "zajištěn"
            self.live_kv.set(
                "Aerokryt · Pyro aktivní / odpáleno",
                f"{cov_txt} ({us[3]} µs)  ·  aktivní: {pa_txt}  /  odpáleno: {pf_txt}",
                BAD if hw.pyro_active else (WARN if hw.pyro_fired else None),
            )
            self.live_kv.set("Tok dat (Pos TX / Master H)", f"TX {tx_n} rámců  /  RX {rx_n} H-snímků")

    def _on_run_finished(self, ok: bool, reason: str, csv_path: str) -> None:
        self._set_controls_enabled(True)
        self.btn_abort.setEnabled(False)
        self.btn_export_as.setEnabled(bool(csv_path and os.path.isfile(csv_path)))

        summ = self.recorder.compute_summary(self.plant)
        col = GOOD if (ok and summ.landed and abs(summ.td_vz_mps) <= 4.0) else (WARN if ok else BAD)
        self.lbl_banner.setText(f"{'DOKONČENO' if ok else 'UKONČENO'} · {summ.verdict}")
        self.lbl_banner.setStyleSheet(
            f"font-size: 18px; font-weight: 700; color: {col}; "
            f"background: {ag.C['surface']}; border: 2px solid {col}; "
            f"border-radius: 10px; padding: 8px;"
        )
        self.prog.setValue(100 if ok else 0)
        self.prog.setFormat(reason)

        # Populate verification summary
        self.sum_kv_l.set("Verdikt", f"{summ.verdict}  ({summ.samples} vzorků, {summ.duration_s:.2f} s)", col)
        self.sum_kv_l.set("Apogeum (pravé / HW odhad)", f"{summ.true_apogee_m:.1f} m  /  {summ.est_apogee_m:.1f} m")
        self.sum_kv_l.set("Chyba výšky (RMSE / max)", f"{summ.alt_rmse_m:.2f} m  /  {summ.alt_max_err_m:.2f} m",
                          GOOD if summ.alt_rmse_m < 2.0 else WARN)
        self.sum_kv_l.set("Výška zážehu (pravá / HW)", f"{summ.h_ign_true_m:.1f} m  /  {summ.h_ign_hw_m:.1f} m")

        self.sum_kv_r.set(
            "Dosednutí (vz / vh / náklon)",
            f"vz {summ.td_vz_mps:+.2f} m/s  ·  vh {summ.td_vh_mps:.2f} m/s  ·  {summ.td_tilt_deg:.1f}°"
            if summ.landed else "nedosedlo",
            GOOD if (summ.landed and abs(summ.td_vz_mps) <= 4.0) else WARN,
        )
        self.sum_kv_r.set(
            "Max TVC / Křidélka / Klapka",
            f"±{summ.max_tvc_deg:.1f}°  /  ±{summ.max_fin_deg:.1f}°  /  {summ.min_clamp*100:.0f}–{summ.max_clamp*100:.0f} %",
        )
        ev_list = []
        if summ.cover_opened:
            ev_list.append("Aerokryt")
        if summ.events_seen & hs.EV_IGN1:
            ev_list.append("Zážeh 1")
        if summ.events_seen & hs.EV_IGN2:
            ev_list.append("Zážeh 2")
        if summ.legs_fired:
            ev_list.append("Nohy")
        py_txt = ",".join(f"P{i+1}" for i in range(3) if summ.pyro_fired_mask & (1 << i)) or "nic"
        self.sum_kv_r.set("Události a pyro", f"{', '.join(ev_list) or '—'}  (pyro: {py_txt})")
        self.sum_kv_r.set("Uložený CSV záznam", os.path.basename(csv_path) if csv_path else "neuloženo",
                          GOOD if csv_path else WARN)

        # Redraw full flight in the 4 verification charts
        if self.recorder.rows:
            span = max(5.0, summ.duration_s + 0.5)
            idx = {name: i for i, name in enumerate(hs.CSV_COLUMNS)}
            for ch in (self.ch_alt, self.ch_tilt, self.ch_tvc, self.ch_fin):
                ch.clear()
                ch.span = span
            step = max(1, len(self.recorder.rows) // 1200)
            for r in self.recorder.rows[::step]:
                t_s = float(r[idx["t_sim"]])
                self.ch_alt.add(t_s, [float(r[idx["true_pz"]]), float(r[idx["est_pz"]])])
                self.ch_tilt.add(t_s, [float(r[idx["true_tilt_deg"]]), float(r[idx["est_tilt_deg"]]),
                                       float(r[idx["tilt_cmd_deg"]])])
                self.ch_tvc.add(t_s, [float(r[idx["cmd_tvc_x_deg"]]), float(r[idx["cmd_tvc_y_deg"]]),
                                      float(r[idx["cmd_clamp"]]) * 10.0])
                self.ch_fin.add(t_s, [float(r[idx["cmd_fin0_deg"]]), float(r[idx["cmd_fin1_deg"]]),
                                      float(r[idx["cmd_fin2_deg"]]), float(r[idx["cmd_fin3_deg"]])])

        if not ok and "Zastaveno uživatelem" not in reason:
            QtWidgets.QMessageBox.warning(self, "HIL simulace ukončena", reason)


