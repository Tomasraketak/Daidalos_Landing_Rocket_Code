"""
"HIL simulace" tab of the diagnostic console (daidalos_diag.py).

Hardware-in-the-Loop flight testing with both Master MCU and Position MCU
connected directly to the PC via USB simultaneously:

  * PC streams 100 Hz binary ARIADNA_PKT_HIL_IN frames (IMU, attitude
    quaternion, barometer, GPS, TF-Luna lidar, UWB ranges) generated by
    hil_sim.py (LandSim_Light 6-DOF vehicle model) into Position MCU's USB.
  * Position MCU runs its real Kalman filter, UWB multilateration, lidar leg
    gate and sends normal ariadna_nav_state_t packets to Master -> Navigation.
  * Master MCU and Navigation MCU run the real flight state machine, guidance,
    sequencer, and move the real PCA9685 actuators (TVC, clamp, fins,
    aerocover). Physical pyro channels on Navigation MCU are INHIBITED by
    default (ARIADNA_MST_PYRO_INHIBIT), with an explicit opt-in checkbox that
    also requires the hardware RBF pin removed.
  * Master MCU streams 50 Hz `H {..}` snapshots back to the PC with both the
    estimated state and the exact commanded angles + PCA9685 microsecond
    pulses. Everything (HIL inputs + HW estimates + HW actuator commands) is
    automatically saved to CSV on the PC at the end of every run.
"""
